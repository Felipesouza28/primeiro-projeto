# Calculadora Python

num1 = int(input("Digite o primeiro numero: "))

num2 = int(input("Digite o segundo número: "))


soma = num1 + num2
print(f"A soma adicao de {num1} e {num2} é igual a = {soma}")

subtracao = num1 - num2
print(f"A soma subtracao de {num1} e {num2} é igual a = {subtracao}")

multiplicacao = num1 * num2
print(f"A soma multiplicacao de {num1} e {num2} é igual a = {multiplicacao}")

divisao = num1 / num2
print(f"A soma divisao de {num1} e {num2} é igual a = {divisao:.2f}")

divisao_inteira = num1 // num2
print(f"A soma divisao inteira de {num1} e {num2} é igual a = {divisao_inteira}")

resto_da_divisao = num1 % num2
print(f"A soma resto da divisao de {num1} e {num2} é igual a = {resto_da_divisao}")

potenciacao = num1 ** num2
print(f"A soma potenciacao de {num1} e {num2} é igual a = {potenciacao}")